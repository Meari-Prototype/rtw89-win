# Print mac\regdb.h (the regulatory rules mac\reg.c applies) from a wireless-regdb regulatory.db, the binary
# database Linux cfg80211 loads (format: net/wireless/reg.c, struct fwdb_*; magic 'RGDB', version 20).
# Only the rules a 2.4/5 GHz channel can fall into are kept (they end above 2400 MHz and start below 5925 MHz).
# The output goes to stdout; the source file is updated by hand from it (no script writes the source tree).
#   .\tools-dev\regdb-gen.ps1 -Path <path to regulatory.db> -Version <wireless-regdb version> > <scratch file>
param([Parameter(Mandatory)] [string]$Path, [Parameter(Mandatory)] [string]$Version)
$Db = $Path
$ErrorActionPreference = 'Stop'
$b = [IO.File]::ReadAllBytes($Db)
$sha = (Get-FileHash -Algorithm SHA256 $Db).Hash.ToLower()
function U16([int]$o) { return ([int]$b[$o] -shl 8) -bor $b[$o + 1] }
function U32([int]$o) { return ([uint32]$b[$o] -shl 24) -bor ([uint32]$b[$o + 1] -shl 16) -bor ([uint32]$b[$o + 2] -shl 8) -bor $b[$o + 3] }
if ((U32 0) -ne 0x52474442) { throw 'not a regulatory.db (magic)' }
if ((U32 4) -ne 20) { throw "regulatory.db version $(U32 4), expected 20" }

$rules = [Collections.Generic.List[string]]::new()      # "start,end,bw,flags" in table order
$ruleIdx = @{}
$lists = [Collections.Generic.List[int]]::new()
$listAt = @{}                                           # collection offset -> index in $lists
$listOf = @{}                                           # list content -> index in $lists (shared by content)
$countries = [Collections.Generic.List[object]]::new()
for ($o = 8; ; $o += 4) {
  $coll = (U16 ($o + 2)) -shl 2
  if ($coll -eq 0) { break }
  $alpha = [char]$b[$o] + [char]$b[$o + 1]
  if (-not $listAt.ContainsKey($coll)) {
    $clen = $b[$coll]; $n = $b[$coll + 1]
    $keep = @()
    for ($i = 0; $i -lt $n; $i++) {
      $r = (U16 ($coll + $clen + ($clen % 2) + 2 * $i)) -shl 2
      if ($b[$r] -lt 16) { throw "rule at $r too short" }
      $start = U32 ($r + 4); $end = U32 ($r + 8); $bw = U32 ($r + 12); $fl = $b[$r + 1]
      if ($end -le 2400000 -or $start -ge 5925000) { continue }
      $key = "$start,$end,$bw,$fl"
      if (-not $ruleIdx.ContainsKey($key)) { $ruleIdx[$key] = $rules.Count; $rules.Add($key) }
      $keep += $ruleIdx[$key]
    }
    $content = $keep -join ','
    if (-not $listOf.ContainsKey($content)) {
      $listOf[$content] = $lists.Count
      $lists.Add($keep.Count)
      foreach ($k in $keep) { $lists.Add($k) }
    }
    $listAt[$coll] = $listOf[$content]
  }
  $countries.Add([pscustomobject]@{ Alpha = $alpha; List = $listAt[$coll]; Dfs = $b[$coll + 2] })
}

