"#define MAC_REGDB_VERSION               `"$Version`""
""
"static const struct mac_reg_rule mac_regdb_rules[$($rules.Count)] = {"
for ($i = 0; $i -lt $rules.Count; $i++) {
  $f = $rules[$i] -split ','
  "`t{{ {0,7}, {1,7}, {2,6}, 0x{3:x2} }},     /* {4} */" -f $f[0], $f[1], $f[2], [int]$f[3], $i
}
"};"
""
"/* per collection: the number of rules, then their indexes in mac_regdb_rules */"
"static const u16 mac_regdb_lists[$($lists.Count)] = {"
$line = "`t"
for ($i = 0; $i -lt $lists.Count; ) {
  $n = $lists[$i]
  $line = "`t" + (($lists.GetRange($i, $n + 1) | ForEach-Object { "$_" }) -join ', ') + ","
  "$line     /* $i */"
  $i += $n + 1
}
"};"
""
"static const struct mac_reg_country mac_regdb_countries[$($countries.Count)] = {"
$row = @()
foreach ($c in $countries) {
  $row += ("{{ `"{0}`", {1,3}, {2} }}," -f $c.Alpha, $c.List, $c.Dfs)
  if ($row.Count -eq 5) { "`t" + ($row -join ' '); $row = @() }
}
if ($row.Count) { "`t" + ($row -join ' ') }
"};"
